class EventWriter:
    """
    Owns PostgreSQL event provenance and delegates vector persistence to
    VectorWriter.

    Token and phrase observations share the event table and Lance event
    space, but retain distinct PostgreSQL provenance through span_end_idx.
    """

    def __init__(
        self,
        conn,
        lance_root: Path,
    ) -> None:
        self.conn = conn
        self.lance_root = lance_root

        self.vector_writers: dict[str, VectorWriter] = {
            scale: VectorWriter(
                lance_root,
                scale=scale,
                model_name=LANCE_MODEL_NAME,
                bucket_size=LANCE_BUCKET_SIZE,
            )
            for scale in ACTIVE_SCALES
        }

    def _writer_for_scale(
        self,
        scale: str,
    ) -> VectorWriter:
        writer = self.vector_writers.get(scale)

        if writer is None:
            writer = VectorWriter(
                self.lance_root,
                scale=scale,
                model_name=LANCE_MODEL_NAME,
                bucket_size=LANCE_BUCKET_SIZE,
            )

            self.vector_writers[scale] = writer

        return writer

    def purge_orphans(
        self,
        conn,
        *,
        year_range=None,
        apply=False,
    ):
        return {
            scale: writer.purge_orphans(
                conn,
                year_range=year_range,
                apply=apply,
            )
            for scale, writer in self.vector_writers.items()
        }

    def write(
        self,
        observations: list[AnyEmbedded],
    ) -> int:
        if not observations:
            return 0

        event_ids = allocate_event_ids(
            self.conn,
            len(observations),
        )

        for embedded, event_id in zip(
            observations,
            event_ids,
        ):
            embedded.observation.event_id = event_id

        self._write_postgres(observations)
        self._write_lance(observations)

        return len(observations)

    def repair_lance(
        self,
        observations: list[AnyEmbedded],
    ) -> int:
        if not observations:
            return 0

        self._resolve_repair_event_ids(observations)

        return self._write_lance(observations)

    def index_existing_tables(self) -> None:
        for writer in self.vector_writers.values():
            writer.index_existing_tables()

    def build_indexes(self) -> None:
        for writer in self.vector_writers.values():
            writer.build_indexes()

    def _write_postgres(
        self,
        observations: list[AnyEmbedded],
    ) -> None:
        if not observations:
            return

        if any(
            embedded.observation.event_id is None
            for embedded in observations
        ):
            raise RuntimeError(
                "Cannot persist observations before PostgreSQL "
                "event IDs have been allocated."
            )

        is_phrase = isinstance(
            observations[0],
            EmbeddedSpanObservation,
        )

        if any(
            isinstance(embedded, EmbeddedSpanObservation) != is_phrase
            for embedded in observations
        ):
            raise RuntimeError( "Cannot write mixed token and phrase observations in a single batch." )


        for item in observations:
            obs = item.observation
            if obs.token_idx is None:
                raise RuntimeError(
                    f"NULL token_idx before PostgreSQL: "
                    f"event_id={obs.event_id!r}, "
                    f"corpus={obs.corpus!r}, "
                    f"doc_id={obs.doc_id!r}, "
                    f"token={obs.token!r}, "
                    f"pub_year={obs.pub_year!r}, "
                    f"observation={obs!r}"
                )

        if is_phrase:
            phrase_observations = [
                embedded
                for embedded in observations
                if isinstance(embedded, EmbeddedSpanObservation)
            ]

            insert_events(
                self.conn,
                event_id=[o.observation.event_id for o in observations],
                corpus=[o.observation.corpus for o in observations],
                doc_id=[o.observation.doc_id for o in observations],
                token=[o.observation.token for o in observations],
                token_idx=[o.observation.token_idx for o in observations],
                span_end_idx=[o.observation.span_end_idx for o in observations],
                pub_year=[o.observation.pub_year for o in observations],
                local_window_id=[o.observation.local_window_id for o in observations],
                local_window_token_pos=[
                    o.observation.local_window_token_pos for o in observations
                ],
                medium_window_id=[o.observation.medium_window_id for o in observations],
                medium_window_token_pos=[
                    o.observation.medium_window_token_pos for o in observations
                ],
                broad_window_id=[o.observation.broad_window_id for o in observations],
                broad_window_token_pos=[
                    o.observation.broad_window_token_pos for o in observations
                ],
            )

        else:
            token_observations = [
                embedded
                for embedded in observations
                if isinstance(embedded, EmbeddedObservation)
            ]

            insert_events(
                self.conn,
                event_id=[o.observation.event_id for o in observations],
                corpus=[o.observation.corpus for o in observations],
                doc_id=[o.observation.doc_id for o in observations],
                token=[o.observation.token for o in observations],
                token_idx=[o.observation.token_idx for o in observations],
                span_end_idx=[None for _ in observations],
                pub_year=[o.observation.pub_year for o in observations],
                local_window_id=[o.observation.local_window_id for o in observations],
                local_window_token_pos=[
                    o.observation.local_window_token_pos for o in observations
                ],
                medium_window_id=[o.observation.medium_window_id for o in observations],
                medium_window_token_pos=[
                    o.observation.medium_window_token_pos for o in observations
                ],
                broad_window_id=[o.observation.broad_window_id for o in observations],
                broad_window_token_pos=[
                    o.observation.broad_window_token_pos for o in observations
                ],
            )

        self.conn.commit()

    def _write_lance(
        self,
        observations: list[AnyEmbedded],
        *,
        scales: tuple[str, ...] = ACTIVE_SCALES,
    ) -> int:

        batches: dict[
            tuple[str, int],
            list[AnyEmbedded],
        ] = defaultdict(list)

        for embedded in observations:
            observation = embedded.observation

            if observation.event_id is None:
                raise RuntimeError(
                    "Cannot write an observation to Lance without "
                    "an authoritative PostgreSQL event ID."
                )

            if observation.pub_year is None:
                raise ValueError(
                    f"Observation {observation.event_id} has no "
                    "publication year and cannot be assigned to "
                    "a chronological Lance table."
                )

            for scale in scales:
                if scale not in embedded.vectors:
                    raise RuntimeError(
                        f"Observation {observation.event_id} has no "
                        f"vector for scale {scale!r}"
                    )

                batches[
                    (scale, observation.pub_year)
                ].append(embedded)

        total_written = 0

        for (scale, pub_year), batch in batches.items():
            writer = self._writer_for_scale(scale)

            event_ids = [
                embedded.observation.event_id
                for embedded in batch
            ]

            vectors = np.stack(
                [
                    embedded.vectors[scale]
                    for embedded in batch
                ]
            )

            total_written += writer.write(
                event_ids=event_ids,
                pub_year=pub_year,
                vectors=vectors,
            )

        return total_written

    def _resolve_repair_event_ids(
        self,
        observations: list[AnyEmbedded],
    ) -> None:
        """
        Resolve repair IDs using complete observation provenance.

        Token identity:
            corpus + doc_id + token_idx + window provenance

        Phrase identity:
            corpus + doc_id + token_idx + span_end_idx +
            window provenance
        """

        for embedded in observations:
            observation = embedded.observation

            if isinstance(
                observation,
                SpanObservation,
            ):
                clauses = [
                    "corpus = %s",
                    "doc_id = %s",
                    "token_idx = %s",
                    "span_end_idx = %s",
                    "local_window_id IS NOT DISTINCT FROM %s",
                    "local_window_token_pos IS NOT DISTINCT FROM %s",
                    "medium_window_id IS NOT DISTINCT FROM %s",
                    "medium_window_token_pos IS NOT DISTINCT FROM %s",
                    "broad_window_id IS NOT DISTINCT FROM %s",
                    "broad_window_token_pos IS NOT DISTINCT FROM %s",
                ]

                params = (
                    observation.corpus,
                    observation.doc_id,
                    observation.token_idx,
                    observation.span_end_idx,
                    observation.local_window_id,
                    observation.local_window_token_pos,
                    observation.medium_window_id,
                    observation.medium_window_token_pos,
                    observation.broad_window_id,
                    observation.broad_window_token_pos,
                )

            else:
                clauses = [
                    "corpus = %s",
                    "doc_id = %s",
                    "token_idx = %s",
                    "span_end_idx IS NULL",
                    "local_window_id IS NOT DISTINCT FROM %s",
                    "local_window_token_pos IS NOT DISTINCT FROM %s",
                    "medium_window_id IS NOT DISTINCT FROM %s",
                    "medium_window_token_pos IS NOT DISTINCT FROM %s",
                    "broad_window_id IS NOT DISTINCT FROM %s",
                    "broad_window_token_pos IS NOT DISTINCT FROM %s",
                ]

                params = (
                    observation.corpus,
                    observation.doc_id,
                    observation.token_idx,
                    observation.local_window_id,
                    observation.local_window_token_pos,
                    observation.medium_window_id,
                    observation.medium_window_token_pos,
                    observation.broad_window_id,
                    observation.broad_window_token_pos,
                )

            with self.conn.cursor() as cur:
                cur.execute(
                    f""" SELECT event_id FROM events WHERE {" AND ".join(clauses)} """,
                    params,
                )

                rows = cur.fetchall()

            if not rows:
                raise RuntimeError(
                    "Lance repair could not find an existing PostgreSQL "
                    "event for observation "
                    f"{observation.corpus}/"
                    f"{observation.doc_id}/"
                    f"{observation.token_idx}"
                )

            if len(rows) > 1:
                raise RuntimeError(
                    "Lance repair found multiple PostgreSQL events for "
                    "the same complete observation provenance: "
                    f"{observation.corpus}/"
                    f"{observation.doc_id}/"
                    f"{observation.token_idx}"
                )

            observation.event_id = int(rows[0][0])


# ---------------------------------------------------------------------------
# Corpus processor
# ---------------------------------------------------------------------------

class CorpusProcessor:
    def __init__(
        self,
        conn,
        pipeline: MacBERThPipeline,
        writer: EventWriter,
        *,
        neighbour_radius: int = NEIGHBOUR_RADIUS,
        report_every: int = 25,
    ) -> None:
        self.conn = conn
        self.pipeline = pipeline
        self.writer = writer
        self.neighbour_radius = neighbour_radius
        self.report_every = report_every

    # ------------------------------------------------------------------
    # Normal token processing
    # ------------------------------------------------------------------

    def process(
        self,
        *,
        corpus: str | None = None,
        doc_id: str | None = None,
    ) -> None:

        documents = self._find_seed_documents(
            corpus=corpus,
            doc_id=doc_id,
        )

        logger.info(
            "[tier1] seed documents: %d",
            len(documents),
        )

        completed_docs_by_corpus: dict[str, set[str]] = {}

        for document_corpus, _document_id in documents:
            if document_corpus not in completed_docs_by_corpus:
                completed_docs_by_corpus[
                    document_corpus
                ] = existing_event_documents(
                    self.writer.conn,
                    corpus=document_corpus,
                    phrases=False,
                )

        for number, (
            document_corpus,
            document_id,
        ) in enumerate(
            documents,
            start=1,
        ):
            completed_docs = completed_docs_by_corpus[
                document_corpus
            ]

            if document_id in completed_docs:
                logger.info(
                    "[tier1] skipping completed token document "
                    "%s/%s",
                    document_corpus,
                    document_id,
                )
                continue

            started = time.perf_counter()

            document = self._load_document(
                document_corpus,
                document_id,
            )

            if document is None:
                continue

            seed_positions = {
                position
                for position, row in enumerate(document.rows)
                if is_seed(row.token)
            }

            if not seed_positions:
                continue

            target_positions = self._select_neighbours(
                seed_positions,
                document,
            )

            embeddings = self.pipeline.embed(
                document,
                target_positions,
            )

            observations = self._build_observations(
                document,
                target_positions,
                embeddings,
            )

            written = self.writer.write(
                observations,
            )

            elapsed = time.perf_counter() - started

            logger.info(
                "[tier1] %3d/%-3d %-4s %-15s "
                "seeds=%3d observations=%5d "
                "written=%5d elapsed=%7.2fs",
                number,
                len(documents),
                document_corpus,
                document_id,
                len(seed_positions),
                len(observations),
                written,
                elapsed,
            )

            completed_docs.add(document_id)

            if number % self.report_every == 0:
                logger.info(
                    "[tier1] processed %d documents",
                    number,
                )

    # ------------------------------------------------------------------
    # Phrase processing
    # ------------------------------------------------------------------

    def process_phrases(
        self,
        *,
        corpus: str | None = None,
        doc_id: str | None = None,
    ) -> None:

        documents = self._find_phrase_documents(
            corpus=corpus,
            doc_id=doc_id,
        )

        logger.info(
            "[tier1] phrase documents: %d",
            len(documents),
        )

        completed_docs_by_corpus: dict[str, set[str]] = {}

        for document_corpus, _document_id in documents:
            if document_corpus not in completed_docs_by_corpus:
                completed_docs_by_corpus[
                    document_corpus
                ] = existing_event_documents(
                    self.writer.conn,
                    corpus=document_corpus,
                    phrases=True,
                )

        for number, (
            document_corpus,
            document_id,
        ) in enumerate(
            documents,
            start=1,
        ):
            completed_docs = completed_docs_by_corpus[
                document_corpus
            ]

            if document_id in completed_docs:
                logger.info(
                    "[tier1] skipping completed phrase document "
                    "%s/%s",
                    document_corpus,
                    document_id,
                )
                continue

            started = time.perf_counter()

            document = self._load_document(
                document_corpus,
                document_id,
            )

            if document is None:
                continue

            spans = self._find_phrase_spans(
                document,
            )

            if not spans:
                continue

            observations: list[EmbeddedSpanObservation] = []

            for (
                start_position,
                end_position,
                phrase,
            ) in spans:

                embeddings = self.pipeline.embed_span(
                    document,
                    start_position,
                    end_position,
                )

                observations.append(
                    self._build_span_observation(
                        document=document,
                        start_position=start_position,
                        end_position=end_position,
                        phrase=phrase,
                        embeddings=embeddings,
                    )
                )

            written = self.writer.write(
                observations,
            )

            elapsed = time.perf_counter() - started

            logger.info(
                "[tier1] phrase %3d/%-3d %-4s %-15s "
                "spans=%5d written=%5d elapsed=%7.2fs",
                number,
                len(documents),
                document_corpus,
                document_id,
                len(observations),
                written,
                elapsed,
            )

            completed_docs.add(document_id)

    # ------------------------------------------------------------------
    # Repair
    # ------------------------------------------------------------------

    def repair(
        self,
        *,
        corpus: str,
        doc_id: str,
        phrases: bool = False,
    ) -> None:

        started = time.perf_counter()

        logger.info(
            "[tier1] repair: %s/%s phrases=%s",
            corpus,
            doc_id,
            phrases,
        )

        document = self._load_document(
            corpus,
            doc_id,
        )

        if document is None:
            raise RuntimeError(
                f"Document not found: {corpus}/{doc_id}"
            )

        if phrases:
            existing = self._load_phrase_events(
                corpus,
                doc_id,
            )

            spans = self._find_phrase_spans(
                document,
            )

            current = {
                (
                    start,
                    end,
                )
                for start, end, _phrase in spans
            }

            stored = {
                (
                    start,
                    end,
                )
                for start, end, _event_id in existing
            }

            if current != stored:
                raise RuntimeError(
                    f"{corpus}/{doc_id}: phrase observation set "
                    "changed since original run "
                    f"(only_current={len(current - stored)}, "
                    f"only_stored={len(stored - current)})."
                )

            observations = []

            for (
                start,
                end,
                phrase,
            ) in spans:

                embeddings = self.pipeline.embed_span(
                    document,
                    start,
                    end,
                )

                observations.append(
                    self._build_span_observation(
                        document=document,
                        start_position=start,
                        end_position=end,
                        phrase=phrase,
                        embeddings=embeddings,
                    )
                )

        else:
            existing = self._load_token_events(
                corpus,
                doc_id,
            )

            seed_positions = {
                position
                for position, row in enumerate(document.rows)
                if is_seed(row.token)
            }

            if not seed_positions:
                raise RuntimeError(
                    f"No seed occurrences found: "
                    f"{corpus}/{doc_id}"
                )

            target_positions = self._select_neighbours(
                seed_positions,
                document,
            )

            expected = {
                document.rows[position].token_idx
                for position in target_positions
            }

            stored = set(existing)

            if expected != stored:
                raise RuntimeError(
                    f"{corpus}/{doc_id}: observation set changed "
                    "since original run "
                    f"(only_expected={len(expected - stored)}, "
                    f"only_stored={len(stored - expected)}). "
                    "Check CONCEPT_SETS / --neighbour-radius."
                )

            embeddings = self.pipeline.embed(
                document,
                target_positions,
            )

            observations = self._build_observations(
                document,
                target_positions,
                embeddings,
            )

        written = self.writer.repair_lance(
            observations,
        )

        elapsed = time.perf_counter() - started

        logger.info(
            "[tier1] repair complete: %-4s %-15s "
            "observations=%5d lance_written=%5d "
            "elapsed=%7.2fs",
            corpus,
            doc_id,
            len(observations),
            written,
            elapsed,
        )

    # ------------------------------------------------------------------
    # Scale backfill
    # ------------------------------------------------------------------

    def backfill_scale(
        self,
        scale: str,
        *,
        corpus: str | None = None,
        doc_id: str | None = None,
    ) -> int:

        if scale not in SCALE_NAMES:
            raise ValueError(
                f"unknown scale {scale!r}"
            )

        writer = self.writer._writer_for_scale(
            scale,
        )

        documents = self._documents_missing_scale(
            scale,
            corpus,
            doc_id,
        )

        logger.info(
            "[backfill:%s] documents to process: %d",
            scale,
            len(documents),
        )

        for number, (
            doc_corpus,
            did,
        ) in enumerate(
            documents,
            start=1,
        ):
            started = time.perf_counter()

            n = self._backfill_document(
                doc_corpus,
                did,
                scale,
                writer,
            )

            logger.info(
                "[backfill:%s] %d/%d %s/%s "
                "events=%d elapsed=%.2fs",
                scale,
                number,
                len(documents),
                doc_corpus,
                did,
                n,
                time.perf_counter() - started,
            )

        writer.index_existing_tables()

        return len(documents)

    def _documents_missing_scale(
        self,
        scale: str,
        corpus: str | None,
        doc_id: str | None,
    ):
        clauses = [
            f"e.{scale}_window_id IS NULL",
        ]

        params: list[object] = []

        if corpus is not None:
            clauses.append(
                "e.corpus = %s"
            )
            params.append(corpus)

        if doc_id is not None:
            clauses.append(
                "e.doc_id = %s"
            )
            params.append(doc_id)

        with self.conn.cursor() as cur:
            cur.execute(
                f"""
                SELECT DISTINCT e.corpus, e.doc_id
                FROM events AS e
                WHERE {" AND ".join(clauses)}
                ORDER BY e.corpus, e.doc_id
                """,
                params,
            )

            return cur.fetchall()

    def _backfill_document(
        self,
        corpus: str,
        doc_id: str,
        scale: str,
        vector_writer: VectorWriter,
    ) -> int:

        document = self._load_document(
            corpus,
            doc_id,
        )

        if document is None:
            raise RuntimeError(
                f"Document not found: {corpus}/{doc_id}"
            )

        token_events = self._load_token_events(
            corpus,
            doc_id,
        )

        phrase_events = self._load_phrase_events(
            corpus,
            doc_id,
        )

        total = 0

        if token_events:
            total += self._backfill_token_events(
                document,
                token_events,
                scale,
                vector_writer,
            )

        if phrase_events:
            total += self._backfill_phrase_events(
                document,
                phrase_events,
                scale,
                vector_writer,
            )

        return total

    def _backfill_token_events(
        self,
        document: DocBuffer,
        events: dict[int, int],
        scale: str,
        vector_writer: VectorWriter,
    ) -> int:

        seed_positions = {
            position
            for position, row in enumerate(document.rows)
            if is_seed(row.token)
        }

        targets = self._select_neighbours(
            seed_positions,
            document,
        )

        expected = {
            document.rows[position].token_idx
            for position in targets
        }

        stored = set(events)

        if expected != stored:
            raise RuntimeError(
                f"{document.corpus}/{document.doc_id}: token "
                "observation set changed since original run "
                f"(only_expected={len(expected - stored)}, "
                f"only_stored={len(stored - expected)})."
            )

        embeddings = self.pipeline.embed(
            document,
            targets,
            scales=(scale,),
        )

        by_year: dict[
            int,
            tuple[list[int], list[np.ndarray]],
        ] = defaultdict(
            lambda: ([], [])
        )

        updates: list[
            tuple[int, int, int]
        ] = []

        for position in sorted(targets):
            row = document.rows[position]

            event_id = events[row.token_idx]

            if row.pub_year is None:
                raise RuntimeError(
                    f"{document.corpus}/{document.doc_id}: "
                    f"event {event_id} has no publication year."
                )

            embedded = embeddings[position][scale]

            ids, vectors = by_year[row.pub_year]

            ids.append(event_id)
            vectors.append(embedded.vector)

            updates.append(
                (
                    embedded.window_id,
                    embedded.window_token_pos,
                    event_id,
                )
            )

        for pub_year, (
            ids,
            vectors,
        ) in by_year.items():

            vector_writer.write(
                event_ids=ids,
                pub_year=pub_year,
                vectors=np.stack(vectors),
            )

        with self.conn.cursor() as cur:
            cur.executemany(
                f"""
                UPDATE events
                SET {scale}_window_id = %s,
                    {scale}_window_token_pos = %s
                WHERE event_id = %s
                """,
                updates,
            )

        self.conn.commit()

        return len(updates)

    def _backfill_phrase_events(
        self,
        document: DocBuffer,
        events: list[
            tuple[int, int, int]
        ],
        scale: str,
        vector_writer: VectorWriter,
    ) -> int:

        current_spans = {
            (
                start,
                end,
            ): phrase
            for start, end, phrase
            in self._find_phrase_spans(document)
        }

        stored_spans = {
            (
                start,
                end,
            )
            for start, end, _event_id
            in events
        }

        if set(current_spans) != stored_spans:
            raise RuntimeError(
                f"{document.corpus}/{document.doc_id}: phrase "
                "observation set changed since original run."
            )

        by_year: dict[
            int,
            tuple[list[int], list[np.ndarray]],
        ] = defaultdict(
            lambda: ([], [])
        )

        updates: list[
            tuple[int, int, int]
        ] = []

        for (
            start,
            end,
            event_id,
        ) in events:

            embeddings = self.pipeline.embed_span(
                document,
                start,
                end,
                scales=(scale,),
            )

            embedded = embeddings[scale]

            pub_year = document.pub_year

            if pub_year is None:
                raise RuntimeError(
                    f"{document.corpus}/{document.doc_id}: "
                    f"phrase event {event_id} has no publication year."
                )

            ids, vectors = by_year[pub_year]

            ids.append(event_id)
            vectors.append(embedded.vector)

            updates.append(
                (
                    embedded.window_id,
                    embedded.window_token_pos,
                    event_id,
                )
            )

        for pub_year, (
            ids,
            vectors,
        ) in by_year.items():

            vector_writer.write(
                event_ids=ids,
                pub_year=pub_year,
                vectors=np.stack(vectors),
            )

        with self.conn.cursor() as cur:
            cur.executemany(
                f"""
                UPDATE events
                SET {scale}_window_id = %s,
                    {scale}_window_token_pos = %s
                WHERE event_id = %s
                """,
                updates,
            )

        self.conn.commit()

        return len(updates)

    # ------------------------------------------------------------------
    # Observation builders
    # ------------------------------------------------------------------

    def _build_observations(
        self,
        document: DocBuffer,
        target_positions: set[int],
        embeddings: dict[ int, dict[str, EmbeddedVector], ],
    ) -> list[EmbeddedObservation]:

        observations: list[ EmbeddedObservation ] = []

        for position in sorted(target_positions):
            row = document.rows[position]

            vectors: dict[str, np.ndarray] = {}
            provenance: dict[ str, EmbeddedVector, ] = {}

            for scale in ACTIVE_SCALES:
                embedded = embeddings[position].get( scale )

                if embedded is None:
                    raise RuntimeError(
                        "Missing embedding provenance for "
                        f"{document.corpus}/{document.doc_id}/"
                        f"{row.token_idx}, scale={scale}"
                    )

                vectors[scale] = embedded.vector
                provenance[scale] = embedded

            local = provenance.get("local")
            medium = provenance.get("medium")
            broad = provenance.get("broad")

            observation = Observation(
                event_id=None,
                corpus=row.corpus,
                doc_id=row.doc_id,
                token=row.token,
                token_idx=row.token_idx,
                pub_year=row.pub_year,

                local_window_id=(
                    local.window_id
                    if local is not None
                    else None
                ),
                local_window_token_pos=(
                    local.window_token_pos
                    if local is not None
                    else None
                ),

                medium_window_id=(
                    medium.window_id
                    if medium is not None
                    else None
                ),
                medium_window_token_pos=(
                    medium.window_token_pos
                    if medium is not None
                    else None
                ),

                broad_window_id=(
                    broad.window_id
                    if broad is not None
                    else None
                ),
                broad_window_token_pos=(
                    broad.window_token_pos
                    if broad is not None
                    else None
                ),
            )

            observations.append(
                EmbeddedObservation(
                    observation=observation,
                    vectors=vectors,
                )
            )

        return observations

    def _build_span_observation(
        self,
        *,
        document: DocBuffer,
        start_position: int,
        end_position: int,
        phrase: str,
        embeddings: dict[
            str,
            EmbeddedVector,
        ],
    ) -> EmbeddedSpanObservation:

        start_row = document.rows[
            start_position
        ]

        vectors = {
            scale: embeddings[scale].vector
            for scale in ACTIVE_SCALES
        }

        local = embeddings.get("local")
        medium = embeddings.get("medium")
        broad = embeddings.get("broad")

        observation = SpanObservation(
            event_id=None,
            corpus=document.corpus,
            doc_id=document.doc_id,
            phrase=phrase,
            token_idx=start_row.token_idx,
            span_end_idx=document.rows[
                end_position - 1
            ].token_idx,
            pub_year=document.pub_year,

            local_window_id=(
                local.window_id
                if local is not None
                else None
            ),
            local_window_token_pos=(
                local.window_token_pos
                if local is not None
                else None
            ),

            medium_window_id=(
                medium.window_id
                if medium is not None
                else None
            ),
            medium_window_token_pos=(
                medium.window_token_pos
                if medium is not None
                else None
            ),

            broad_window_id=(
                broad.window_id
                if broad is not None
                else None
            ),
            broad_window_token_pos=(
                broad.window_token_pos
                if broad is not None
                else None
            ),
        )

        return EmbeddedSpanObservation(
            observation=observation,
            vectors=vectors,
        )

    # ------------------------------------------------------------------
    # Corpus lookup
    # ------------------------------------------------------------------

    def _find_seed_documents(
        self,
        *,
        corpus: str | None,
        doc_id: str | None,
    ) -> list[tuple[str, str]]:

        clauses = [
            "lower(t.token) = ANY(%s)",
        ]

        params: list[object] = [
            sorted(
                SEED_FORMS - FALSE_POSITIVE_FORMS
            ),
        ]

        if corpus is not None:
            clauses.append(
                "t.corpus = %s"
            )
            params.append(corpus)

        if doc_id is not None:
            clauses.append(
                "t.doc_id = %s"
            )
            params.append(doc_id)

        sql = f"""
            SELECT DISTINCT t.corpus, t.doc_id
            FROM pamphlet_tokens AS t
            WHERE {" AND ".join(clauses)}
            ORDER BY t.corpus, t.doc_id
        """

        with self.conn.cursor() as cur:
            cur.execute(
                sql,
                params,
            )

            return cur.fetchall()

    def _find_phrase_documents(
        self,
        *,
        corpus: str | None,
        doc_id: str | None,
    ) -> list[tuple[str, str]]:

        if not PHRASE_FORMS:
            return []

        first_tokens = sorted(
            {
                phrase[0]
                for phrase in PHRASE_FORMS
                if phrase
            }
        )

        clauses = [
            "lower(t.token) = ANY(%s)",
        ]

        params: list[object] = [
            first_tokens,
        ]

        if corpus is not None:
            clauses.append(
                "t.corpus = %s"
            )
            params.append(corpus)

        if doc_id is not None:
            clauses.append(
                "t.doc_id = %s"
            )
            params.append(doc_id)

        sql = f"""
            SELECT DISTINCT t.corpus, t.doc_id
            FROM pamphlet_tokens AS t
            WHERE {" AND ".join(clauses)}
            ORDER BY t.corpus, t.doc_id
        """

        with self.conn.cursor() as cur:
            cur.execute(
                sql,
                params,
            )

            return cur.fetchall()


    def _load_document(
        self,
        corpus: str,
        doc_id: str,
    ) -> DocBuffer | None:

        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT t.corpus, t.doc_id, t.token_idx, t.token, d.pub_year
                FROM pamphlet_tokens AS t
                JOIN pamphlet_corpus AS d
                  ON d.corpus = t.corpus
                 AND d.doc_id = t.doc_id
                WHERE t.corpus = %s
                  AND t.doc_id = %s
                ORDER BY t.token_idx
                """,
                (
                    corpus,
                    doc_id,
                ),
            )

            rows = cur.fetchall()

            if not rows:
                return None

            token_rows = [
                TokenRow(
                    corpus=row[0],
                    doc_id=row[1],
                    token_idx=row[2],
                    token=row[3],
                    pub_year=row[4],
                )
                for row in rows
            ]

            for row in token_rows:
                if row.doc_id == "A01289" and row.token.lower() == "clotho":
                    logger.debug("DEBUG TOKEN ROW: %r", row)

            return DocBuffer(
                corpus=corpus,
                doc_id=doc_id,
                pub_year=token_rows[0].pub_year,
                rows=token_rows,
            )


    # ------------------------------------------------------------------
    # Phrase matching
    # ------------------------------------------------------------------

    def _find_phrase_spans(
        self,
        document: DocBuffer,
    ) -> list[
        tuple[int, int, str]
    ]:

        normalised = [
            normalise_token(row.token)
            for row in document.rows
        ]

        spans: list[
            tuple[int, int, str]
        ] = []

        for phrase in PHRASE_FORMS:
            length = len(phrase)

            if length == 0:
                continue

            for start in range(
                0,
                len(normalised) - length + 1,
            ):
                if tuple(
                    normalised[
                        start:start + length
                    ]
                ) != phrase:
                    continue

                end = start + length

                spans.append(
                    (
                        start,
                        end,
                        " ".join(phrase),
                    )
                )

        spans.sort(
            key=lambda item: (
                item[0],
                item[1],
                item[2],
            )
        )

        return spans

    # ------------------------------------------------------------------
    # Neighbours
    # ------------------------------------------------------------------

    def _select_neighbours(
        self,
        seed_positions: set[int],
        document: DocBuffer,
    ) -> set[int]:

        positions: set[int] = set()

        for seed_position in seed_positions:
            start = max(
                0,
                seed_position - self.neighbour_radius,
            )

            end = min(
                len(document.rows),
                seed_position + self.neighbour_radius + 1,
            )

            positions.update(
                position
                for position in range(
                    start,
                    end,
                )
                if (
                    position in seed_positions
                    or is_storable_event(
                        document.rows[position].token
                    )
                )
            )

        return positions

    # ------------------------------------------------------------------
    # Existing event loading
    # ------------------------------------------------------------------

    def _load_token_events(
        self,
        corpus: str,
        doc_id: str,
    ) -> dict[int, int]:

        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT
                    token_idx,
                    event_id
                FROM events
                WHERE corpus = %s
                  AND doc_id = %s
                  AND span_end_idx IS NULL
                ORDER BY token_idx
                """,
                (
                    corpus,
                    doc_id,
                ),
            )

            rows = cur.fetchall()

        events: dict[int, int] = {}

        for token_idx, event_id in rows:
            if token_idx in events:
                raise RuntimeError(
                    f"{corpus}/{doc_id}: multiple token events "
                    f"at token_idx={token_idx}"
                )

            events[int(token_idx)] = int(event_id)

        return events

    def _load_phrase_events(
        self,
        corpus: str,
        doc_id: str,
    ) -> list[
        tuple[int, int, int]
    ]:

        with self.conn.cursor() as cur:
            cur.execute(
                """
                SELECT
                    token_idx,
                    span_end_idx,
                    event_id
                FROM events
                WHERE corpus = %s
                  AND doc_id = %s
                  AND span_end_idx IS NOT NULL
                ORDER BY token_idx, span_end_idx
                """,
                (
                    corpus,
                    doc_id,
                ),
            )

            rows = cur.fetchall()

        return [
            (
                int(token_idx),
                int(span_end_idx),
                int(event_id),
            )
            for token_idx, span_end_idx, event_id
            in rows
        ]


