def parse_repair_target(
    value: str,
) -> tuple[str, str]:

    if "/" not in value:
        raise argparse.ArgumentTypeError(
            "repair target must be CORPUS/DOC_ID"
        )

    corpus, doc_id = value.split(
        "/",
        1,
    )

    if not corpus or not doc_id:
        raise argparse.ArgumentTypeError(
            "repair target must be CORPUS/DOC_ID"
        )

    return corpus, doc_id


def repair_year_range(
    processor: CorpusProcessor,
    conn,
    start_year: int,
    end_year: int,
    corpus: str | None = None,
) -> int:

    if start_year > end_year:
        raise ValueError(
            f"start_year ({start_year}) must not exceed "
            f"end_year ({end_year})"
        )

    bucket_start = (
        start_year // LANCE_BUCKET_SIZE
    ) * LANCE_BUCKET_SIZE

    bucket_end = (
        (end_year // LANCE_BUCKET_SIZE) + 1
    ) * LANCE_BUCKET_SIZE - 1

    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT DISTINCT e.corpus, e.doc_id, e.pub_year
            FROM events AS e
            WHERE (%s::text IS NULL OR e.corpus = %s)
              AND e.pub_year BETWEEN %s AND %s
            ORDER BY
                e.pub_year,
                e.corpus,
                e.doc_id
            """,
            (
                corpus,
                corpus,
                bucket_start,
                bucket_end,
            ),
        )

        documents = cur.fetchall()

    logger.info(
        "[repair] Requested years %d-%d; repairing complete "
        "buckets %d-%d; %d documents "
        "(corpus=%s)",
        start_year,
        end_year,
        bucket_start,
        bucket_end,
        len(documents),
        corpus or "all",
    )

    repaired = 0

    for number, (
        doc_corpus,
        doc_id,
        pub_year,
    ) in enumerate(
        documents,
        start=1,
    ):
        logger.info(
            "[repair] %d/%d %s/%s "
            "(pub_year=%s)",
            number,
            len(documents),
            doc_corpus,
            doc_id,
            pub_year,
        )

        processor.repair(
            corpus=doc_corpus,
            doc_id=doc_id,
            phrases=False,
        )

        repaired += 1

    results = processor.writer.purge_orphans(
        conn,
        year_range=(
            bucket_start,
            bucket_end,
        ),
        apply=True,
    )

    logger.info(
        "[repair] purged orphans: %s",
        results,
    )

    logger.info(
        "[repair] Repaired %d documents "
        "for buckets %d-%d",
        repaired,
        bucket_start,
        bucket_end,
    )

    return repaired


