def parse_args() -> argparse.Namespace:

    parser = argparse.ArgumentParser(
        description=(
            "Build Tier 1 token and phrase observations from "
            "the restricted pamphlet corpus through MacBERTh "
            "into Lance."
        )
    )

    parser.add_argument(
        "--corpus",
        default=None,
    )

    parser.add_argument(
        "--doc-id",
        default=None,
    )

    parser.add_argument(
        "--neighbour-radius",
        type=int,
        default=256,
    )

    parser.add_argument(
        "--lance-root",
        type=Path,
        default=Path(LANCE_INDEXES_DIR),
    )

    parser.add_argument(
        "--batch-size",
        type=int,
        default=EMBED_BATCH_SIZE,
    )

    parser.add_argument(
        "--report-every",
        type=int,
        default=1,
    )

    parser.add_argument(
        "--phrases",
        action="store_true",
        help="Process phrase observations rather than token observations.",
    )

    parser.add_argument(
        "--add-scale",
        choices=SCALE_NAMES,
        default=None,
        help=(
            "Add this scale to existing observations without "
            "creating new event IDs."
        ),
    )

    parser.add_argument(
        "--mask",
        action="store_true",
        help=(
            "Replace target tokens with [MASK] before embedding."
        ),
    )

    parser.add_argument(
        "--index-only",
        action="store_true",
        help=(
            "Rebuild incomplete indexes on existing active-scale "
            "Lance tables."
        ),
    )

    parser.add_argument(
        "--repair",
        type=parse_repair_target,
        metavar="CORPUS/DOC_ID",
        help=(
            "Regenerate Lance vectors for one token-observation "
            "document without modifying PostgreSQL events."
        ),
    )

    parser.add_argument(
        "--repair-years",
        nargs=2,
        type=int,
        metavar=("START_YEAR", "END_YEAR"),
        help=(
            "Repair all token-observation documents in the "
            "complete 50-year Lance buckets containing this range."
        ),
    )

    parser.add_argument(
        "--skip-indexing",
        action="store_true",
        help=(
            "Skip the post-run Lance index rebuild."
        ),
    )

    # -- Job queue ---------------------------------------------------------

    parser.add_argument(
        "--populate",
        action="store_true",
        help=(
            "Enqueue jobs (one per document) instead of processing. "
            "Combine with --phrases or --add-scale to pick the job kind; "
            "--corpus, --doc-id, --min-year and --max-year narrow it."
        ),
    )

    parser.add_argument(
        "--worker",
        action="store_true",
        help=(
            "Claim and process queued jobs until none remain. "
            "Combine with --phrases or --add-scale to pick the job kind."
        ),
    )

    parser.add_argument(
        "--min-year",
        type=int,
        default=None,
        help="With --populate: only documents published in/after this year.",
    )

    parser.add_argument(
        "--max-year",
        type=int,
        default=None,
        help="With --populate: only documents published in/before this year.",
    )

    parser.add_argument(
        "--worker-id",
        default=None,
        help="With --worker: identifier recorded on claimed jobs.",
    )

    parser.add_argument(
        "--max-docs",
        type=int,
        default=None,
        help="With --worker: stop after this many jobs (useful for testing).",
    )

    parser.add_argument(
        "--dry-run",
        action="store_true",
        help=(
            "With --worker: embed the first pending job but write nothing "
            "and leave jobs untouched."
        ),
    )

    args = parser.parse_args()

    if args.repair is not None and (
        args.corpus is not None
        or args.doc_id is not None
    ):
        parser.error(
            "--repair cannot be combined with "
            "--corpus or --doc-id"
        )

    if args.repair is not None and args.repair_years:
        parser.error(
            "--repair and --repair-years cannot "
            "be used together"
        )

    if args.index_only and any(
        (
            args.repair,
            args.repair_years,
            args.add_scale,
            args.phrases,
        )
    ):
        parser.error(
            "--index-only cannot be combined with "
            "processing, repair, or backfill options"
        )

    # -- Job queue validation ----------------------------------------------

    if args.populate and args.worker:
        parser.error(
            "--populate and --worker cannot be used together"
        )

    if (args.populate or args.worker) and (
        args.repair is not None
        or args.repair_years
        or args.index_only
    ):
        parser.error(
            "--populate/--worker cannot be combined with "
            "--repair, --repair-years or --index-only"
        )

    if args.worker and (
        args.corpus is not None
        or args.doc_id is not None
    ):
        parser.error(
            "--worker claims whatever is queued; narrow the queue with "
            "--corpus/--doc-id at --populate time instead"
        )

    # These only act on the queue. Rejecting them elsewhere means a
    # direct run can never be mistaken for a dry run.
    if args.dry_run and not args.worker:
        parser.error("--dry-run requires --worker")

    if (
        args.worker_id is not None
        or args.max_docs is not None
    ) and not args.worker:
        parser.error("--worker-id and --max-docs require --worker")

    if (
        args.min_year is not None
        or args.max_year is not None
    ) and not args.populate:
        parser.error("--min-year and --max-year require --populate")

    return args


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:

    args = parse_args()

    torch.set_num_threads(
        int(
            os.environ.get(
                "OMP_NUM_THREADS",
                "4",
            )
        )
    )

    torch.set_num_interop_threads(1)

    conn = get_connection(
        application_name="tier1-phrases2events",
    )

    if not args.worker and not os.environ.get("COLAB_MODE"):
        create_events_table(conn)

    if args.index_only:
        try:
            writer = EventWriter( conn, args.lance_root, )
            writer.index_existing_tables()
        finally:
            conn.close()

        return

    if args.populate:
        # Enqueue only: needs the database, not MacBERTh or Lance.
        try:
            ensure_jobs_table(conn)

            kind = job_kind(
                phrases=args.phrases,
                add_scale=args.add_scale,
            )

            logger.info(
                "[tier1] populating %s jobs",
                kind,
            )

            processor = CorpusProcessor(
                conn,
                None,
                None,
                neighbour_radius=args.neighbour_radius,
                report_every=args.report_every,
            )

            created = processor.populate_jobs(
                kind,
                corpus=args.corpus,
                doc_id=args.doc_id,
                min_year=args.min_year,
                max_year=args.max_year,
            )

            logger.info(
                "[tier1] populated %d %s jobs",
                created,
                kind,
            )
        finally:
            conn.close()

        return

    try:
        if args.worker:
            ensure_jobs_table(conn)

        mac = load_macberth()

        pipeline = MacBERThPipeline(
            mac,
            batch_size=args.batch_size,
            mask_targets=args.mask,
        )

        writer = EventWriter(
            conn,
            args.lance_root,
        )

        processor = CorpusProcessor(
            conn,
            pipeline,
            writer,
            neighbour_radius=args.neighbour_radius,
            report_every=args.report_every,
        )

        if args.worker:
            kind = job_kind(
                phrases=args.phrases,
                add_scale=args.add_scale,
            )

            processor.process_queue(
                kind=kind,
                worker_id=args.worker_id,
                max_docs=args.max_docs,
                dry_run=args.dry_run,
                skip_indexing=args.skip_indexing,
            )

            if backfill_scale_for_kind(kind) is not None:
                # Like --add-scale: indexing of the backfilled scale
                # was already handled by process_queue().
                return

        elif args.repair:

            corpus, doc_id = args.repair

            processor.repair(
                corpus=corpus,
                doc_id=doc_id,
                phrases=args.phrases,
            )

        elif args.repair_years:

            start_year, end_year = args.repair_years

            repair_year_range(
                processor=processor,
                conn=conn,
                start_year=start_year,
                end_year=end_year,
                corpus=args.corpus,
            )

        elif args.add_scale:

            processor.backfill_scale(
                args.add_scale,
                corpus=args.corpus,
                doc_id=args.doc_id,
            )

            return

        elif args.phrases:

            processor.process_phrases(
                corpus=args.corpus,
                doc_id=args.doc_id,
            )

        else:

            processor.process(
                corpus=args.corpus,
                doc_id=args.doc_id,
            )

        if args.dry_run:
            logger.info(
                "[tier1] --dry-run set; not building indexes"
            )
        elif args.skip_indexing:
            logger.info(
                "[tier1] --skip-indexing set; leaving "
                "index (re)build for a later run"
            )
        else:
            writer.build_indexes()

    finally:
        conn.close()


if __name__ == "__main__":
    main()
